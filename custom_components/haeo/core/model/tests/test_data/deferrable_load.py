def _opened_at_window_starts(in_window: Sequence[float], window_start: Sequence[float], due: Sequence[float]) -> list[float]:
    """Open each due amount at the start of its window, as for one event per window."""
    opened = [0.0] * len(due)
    for end, amount in enumerate(due):
        if amount:
            start = end - 1
            while start > 0 and in_window[start - 1] and not window_start[start]:
                start -= 1
            opened[start] += amount
    return opened


def _case(
    description: str,
    *,
    in_window: Sequence[float],
    window_start: Sequence[float],
    due: Sequence[float],
    expected_outputs: dict[str, ExpectedOutput],
    expected_cost: float,
    opened: Sequence[float] | None = None,
    deficit_price: Sequence[float] | float = 10.0,
    initial_energy: float = 0.0,
    overage_price: Sequence[float] | float = 0.0,
    supply_price: Sequence[float] | None = None,
    max_supply_power: Sequence[float] | None = None,
) -> ElementTestCase:
    """Return a case for a load fed by a supply at 0.1 per kWh unless priced otherwise."""
    n = len(in_window)
    boundaries = n + 1
    return {
        "description": description,
        "factory": DeferrableLoad,
        "data": {
            "name": "load",
            "periods": np.ones(n),
            "in_window": np.asarray(in_window, dtype=np.float64),
            "window_start": np.asarray(window_start, dtype=np.float64),
            "opened": np.asarray(
                opened if opened is not None else _opened_at_window_starts(in_window, window_start, due),
                dtype=np.float64,
            ),
            "due": np.asarray(due, dtype=np.float64),
            "deficit_price": np.broadcast_to(np.asarray(deficit_price, dtype=np.float64), boundaries).copy(),
            "overage_price": np.broadcast_to(np.asarray(overage_price, dtype=np.float64), boundaries).copy(),
            "initial_energy": initial_energy,
        },
        "inputs": {
            "input_cost": np.asarray(supply_price if supply_price is not None else [0.1] * n, dtype=np.float64),
            "max_power": max_supply_power if max_supply_power is not None else [np.inf] * n,
            "min_power": [0.0] * n,
        },
        "expected_outputs": expected_outputs,
        "expected_cost": expected_cost,
    }


